import { describe, expect, it, vi } from 'vitest'
import { adminApi } from './admin-api'

describe('administrator governance API contracts', () => {
  it('uses bounded explicit batch inputs with independent server outcomes', async () => {
    const request = vi.fn<Parameters<typeof adminApi>[0]>().mockResolvedValue({ items: [] })
    const api = adminApi(request as Parameters<typeof adminApi>[0])
    await api.previewBulkApprovals(['r1', 'r2'])
    expect(request).toHaveBeenLastCalledWith('/api/v1/access-requests/bulk/preview', { method: 'POST', body: { requestIds: ['r1', 'r2'] } })
    await api.approveBulkRequests({ idempotencyKey: 'stable-key', items: [{ requestId: 'r1', approval: {} }] })
    expect(request).toHaveBeenLastCalledWith('/api/v1/access-requests/bulk/approve', { method: 'POST', body: { idempotencyKey: 'stable-key', items: [{ requestId: 'r1', approval: {} }] } })
  })
  it('uses self-scoped inbox paths and server snake_case pagination without identity parameters', async () => {
    const request = vi.fn<Parameters<typeof adminApi>[0]>().mockResolvedValue({})
    const api = adminApi(request as Parameters<typeof adminApi>[0])
    await api.listNotificationInbox({ category: 'requestLifecycle', unreadOnly: true, continuationToken: 'opaque+token' })
    expect(request).toHaveBeenLastCalledWith('/api/v1/notifications/me/inbox?category=requestLifecycle&unread_only=true&continuation_token=opaque%2Btoken')
    await api.setNotificationRead('item/id', true)
    expect(request).toHaveBeenLastCalledWith('/api/v1/notifications/me/inbox/item%2Fid', { method: 'PATCH', body: { read: true } })
  })
  it('does not invoke model tests or recommendations when checking readiness', async () => {
    const request = vi.fn<Parameters<typeof adminApi>[0]>().mockResolvedValue({})
    const api = adminApi(request as Parameters<typeof adminApi>[0])
    await api.getApprovalAiReadiness()
    expect(request).toHaveBeenCalledExactlyOnceWith('/api/v1/approval-ai/readiness')
    await api.recommendApprovals(['request'])
    expect(request).toHaveBeenLastCalledWith('/api/v1/approval-ai/recommend', { method: 'POST', body: { requestIds: ['request'] } })
    await api.getApprovalRecommendations('request/id')
    expect(request).toHaveBeenLastCalledWith('/api/v1/access-requests/request%2Fid/recommendation')
  })
  it('matches the final saved-policy, evaluator and governed-model routes', async () => {
    const request = vi.fn<Parameters<typeof adminApi>[0]>().mockResolvedValue({})
    const api = adminApi(request as Parameters<typeof adminApi>[0])
    await api.listApprovalPolicies()
    expect(request).toHaveBeenLastCalledWith('/api/v1/approval-policies')
    await api.previewApprovalPolicy('policy/id', ['r1'])
    expect(request).toHaveBeenLastCalledWith('/api/v1/approval-policies/policy%2Fid/preview', { method: 'POST', body: { requestIds: ['r1'] } })
    await api.getApprovalEvaluator()
    expect(request).toHaveBeenLastCalledWith('/api/v1/approval-evaluator')
    await api.setApprovalEvaluator(false)
    expect(request).toHaveBeenLastCalledWith('/api/v1/approval-evaluator', { method: 'PUT', body: { paused: false } })
    await api.getApprovalAiSettings()
    expect(request).toHaveBeenLastCalledWith('/api/v1/settings/approval-ai')
    await api.listApprovalAiOfferings()
    expect(request).toHaveBeenLastCalledWith('/api/v1/approval-ai/offerings')
    await api.testApprovalAi()
    expect(request).toHaveBeenLastCalledWith('/api/v1/approval-ai/test', { method: 'POST' })
  })
  it('passes conditional revision on policy deletion and keeps missing endpoints explicit errors', async () => {
    const request = vi.fn<Parameters<typeof adminApi>[0]>().mockResolvedValue(undefined)
    const api = adminApi(request as Parameters<typeof adminApi>[0])
    await api.deleteApprovalPolicy('policy/id', 3)
    expect(request).toHaveBeenCalledWith('/api/v1/approval-policies/policy%2Fid?expected_revision=3', { method: 'DELETE' })
    request.mockRejectedValueOnce(new Error('Request failed with status 404'))
    await expect(api.getNotificationHealth()).rejects.toThrow('404')
  })
})
